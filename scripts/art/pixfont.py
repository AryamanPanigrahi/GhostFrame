ADVANCE = 6  # pixels per character, including 1 pixel of spacing
CAP_ROWS = 7  # rows above the baseline
DESC_ROWS = 2  # rows below it


def glyph(ch):
    return GLYPHS.get(ch, GLYPHS["?"])


def text_pixels(text):
    """Yields (x, y) pixel coordinates of `text`, y = 0 at the top of the caps."""
    for i, ch in enumerate(text):
        for y, row in enumerate(glyph(ch)):
            for x, c in enumerate(row):
                if c == "#":
                    yield i * ADVANCE + x, y


def text_width(text):
    return len(text) * ADVANCE - 1
